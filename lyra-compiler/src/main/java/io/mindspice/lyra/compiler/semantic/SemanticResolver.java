    private record Use(
            Optional<DeclDraft> declaration,
            Optional<ModuleId> module,
            Optional<ResolvedExport> export,
            Optional<LyraSignature> signature,
            Optional<ReferenceId> reference,
            Optional<LyraType> type,
            ValueAlternatives ownershipValues,
            List<AggregateIdentityFact> mutationContainerFacts,
            Set<DeclarationId> selfAliases) {
        private Use {
            declaration = Objects.requireNonNull(declaration, "declaration");
            module = Objects.requireNonNull(module, "module");
            export = Objects.requireNonNull(export, "export");
            signature = Objects.requireNonNull(signature, "signature");
            reference = Objects.requireNonNull(reference, "reference");
            type = Objects.requireNonNull(type, "type");
            ownershipValues = Objects.requireNonNull(ownershipValues, "ownershipValues");
            mutationContainerFacts = canonicalFacts(mutationContainerFacts);
            selfAliases = Set.copyOf(selfAliases);
        }

        private static List<AggregateIdentityFact> canonicalFacts(
                List<? extends AggregateIdentityFact> facts) {
            LinkedHashSet<AggregateIdentityFact> unique = new LinkedHashSet<>();
            for (AggregateIdentityFact fact : Objects.requireNonNull(facts, "facts")) {
                unique.add(Objects.requireNonNull(fact, "facts must not contain null"));
            }
            return unique.stream().sorted(AggregateIdentityFact.comparator()).toList();
        }

        private static Use empty() {
            return new Use(Optional.empty(), Optional.empty(), Optional.empty(),
                    Optional.empty(), Optional.empty(), Optional.empty(),
                    ValueAlternatives.empty(), List.of(), Set.of());
        }

        private static Use lambda(LyraSignature signature) {
            FunctionType type = signature.asFunctionType();
            return new Use(Optional.empty(), Optional.empty(), Optional.empty(),
                    Optional.of(signature), Optional.empty(), Optional.of(type),
                    ValueAlternatives.singleton(ValueAlternative.scalar(type)), List.of(), Set.of());
        }

        private static Use value(LyraType type) {
            LyraType valueType = Objects.requireNonNull(type, "type");
            return new Use(Optional.empty(), Optional.empty(), Optional.empty(),
                    Optional.empty(), Optional.empty(), Optional.of(valueType),
                    ValueAlternatives.singleton(ValueAlternative.scalar(valueType)), List.of(), Set.of());
        }

        private static Use aggregateValue(LyraType type, List<Use> members) {
            return aggregate(Optional.of(Objects.requireNonNull(type, "type")), members);
        }

        private static Use aggregate(Optional<LyraType> type, List<Use> members) {
            Objects.requireNonNull(type, "type");
            Objects.requireNonNull(members, "members");
            LyraType aggregateType = type.orElse(null);
            if (aggregateType == null) {
                return empty();
            }
            List<AggregateAlternativeParts> combinations = List.of(
                    new AggregateAlternativeParts(List.of()));
            for (int index = 0; index < members.size(); index++) {
                ProjectionStep step = aggregateType.withoutQualifiers() instanceof TupleType
                        ? ProjectionStep.tupleMember(index)
                        : ProjectionStep.arrayElement(index);
                ProjectionPath prefix = ProjectionPath.of(step);
                List<ValueAlternative> memberAlternatives =
                        members.get(index).ownershipValues.alternatives();
                if (memberAlternatives.isEmpty()) {
                    memberAlternatives = List.of(ValueAlternative.scalar(
                            ValueAlternative.typeAt(aggregateType, prefix)));
                }
                ArrayList<AggregateAlternativeParts> next = new ArrayList<>();
                for (AggregateAlternativeParts current : combinations) {
                    for (ValueAlternative member : memberAlternatives) {
                        ArrayList<AggregateIdentityFact> facts = new ArrayList<>(
                                current.aggregateIdentities());
                        facts.addAll(member.aggregateIdentities().stream()
                                .map(fact -> fact.prefixedBy(prefix))
                                .toList());
                        next.add(new AggregateAlternativeParts(facts));
                    }
                }
                combinations = List.copyOf(next);
            }
            ArrayList<ValueAlternative> aggregateAlternatives = new ArrayList<>();
            for (AggregateAlternativeParts parts : combinations) {
                try {
                    aggregateAlternatives.add(ValueAlternative.of(
                            aggregateType, parts.aggregateIdentities()));
                } catch (IllegalArgumentException incompatibleMember) {
                    // The checker owns structural/type incompatibility
                    // diagnostics. Do not let a provisional ownership route
                    // turn an expected source error into an implementation
                    // exception.
                    aggregateAlternatives.add(ValueAlternative.scalar(
                            aggregateType));
                }
            }
            return new Use(Optional.empty(), Optional.empty(), Optional.empty(),
                    Optional.empty(), Optional.empty(), type,
                    new ValueAlternatives(aggregateAlternatives), List.of(),
                    members.stream().map(Use::selfAliases)
                            .flatMap(Set::stream).collect(java.util.stream.Collectors.toSet()));
        }

        private static Use mergedValue(LyraType type, List<Use> values) {
            return merged(Optional.of(Objects.requireNonNull(type, "type")), values);
        }

        private static Use merged(Optional<LyraType> type, List<Use> values) {
            Objects.requireNonNull(type, "type");
            Objects.requireNonNull(values, "values");
            ValueAlternatives ownershipValues = ValueAlternatives.empty();
            for (Use value : values) {
                ownershipValues = ownershipValues.join(value.ownershipValues);
            }
            if (ownershipValues.isEmpty() && type.isPresent()) {
                ownershipValues = ValueAlternatives.singleton(
                        ValueAlternative.scalar(type.orElseThrow()));
            }
            return new Use(Optional.empty(), Optional.empty(), Optional.empty(),
                    Optional.empty(), Optional.empty(), type, ownershipValues, List.of(),
                    values.stream().map(Use::selfAliases)
                            .flatMap(Set::stream).collect(java.util.stream.Collectors.toSet()));
        }

        private Use withOwnershipValues(ValueAlternatives values) {
            return new Use(declaration, module, export, signature, reference, type,
                    values, mutationContainerFacts, selfAliases);
        }

        private Use selectedProjection(
                Optional<LyraType> selectedType,
                ProjectionPath selection) {
            ValueAlternatives selected = ownershipValues.isEmpty()
                    ? ValueAlternatives.empty()
                    : selectAggregateValues(ownershipValues, selection);
            List<AggregateIdentityFact> containers = ownershipValues.alternatives().stream()
                    .flatMap(value -> value.aggregateIdentities().stream())
                    .filter(fact -> fact.route().isRoot())
                    .toList();
            return new Use(declaration, module, export, Optional.empty(), reference,
                    selectedType, selected, containers, selfAliases);
        }

        private static ValueAlternatives selectAggregateValues(
                ValueAlternatives values, ProjectionPath selection) {
            try {
                return values.select(selection);
            } catch (IllegalArgumentException incompatibleRoute) {
                return ValueAlternatives.empty();
            }
        }
    }
